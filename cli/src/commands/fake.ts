/**
 * Hidden CLI command for simulating workflow runs.
 *
 * Emits real events into the rp1 event pipeline without executing agents,
 * enabling rapid, repeatable UI testing of the Web UI dashboard.
 */

import { dirname } from "node:path";
import chalk from "chalk";
import { Command } from "commander";
import * as E from "fp-ts/lib/Either.js";
import { executeEmit } from "../agent-tools/emit/index.js";
import type { EmitInput } from "../agent-tools/emit/models.js";
import { resolveRp1Root } from "../agent-tools/rp1-root-dir/resolver.js";
import {
	deriveOrderedSteps,
	loadStateMachine,
	type OrderedStep,
} from "../agent-tools/state-machine/index.js";

type Speed = "fast" | "normal" | "slow";

interface FakeOptions {
	readonly speed: Speed;
	readonly feature?: string;
	readonly failAt?: string;
	readonly pauseAt?: string;
	readonly withBtw: boolean;
	readonly withArtifacts: boolean;
	readonly withSubflows: boolean;
	readonly count: number;
}

/** Parse the command string to extract the workflow name. */
export const parseWorkflowName = (commandStr: string): string => {
	const trimmed = commandStr.trim().replace(/^\/+/, "");
	const firstToken = trimmed.split(/\s+/)[0];
	return firstToken;
};

/** Generate a feature ID from the --feature option or a timestamp. */
export const generateFeatureId = (featureOption?: string): string => {
	if (featureOption) return featureOption;
	return `fake-${Date.now()}`;
};

/** Generate a fake-prefixed run ID. */
export const generateRunId = (): string => {
	return `fake-${crypto.randomUUID()}`;
};

/** Get the delay range for a given speed setting. */
const getDelayMs = (speed: Speed): number => {
	switch (speed) {
		case "fast":
			return 500;
		case "normal":
			return 2000 + Math.random() * 3000;
		case "slow":
			return 5000 + Math.random() * 10000;
	}
};

