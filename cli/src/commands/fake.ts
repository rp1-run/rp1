/** Resolve the project path using resolveRp1Root with cwd fallback. */
const resolveProjectPath = async (): Promise<string> => {
	const result = await resolveRp1Root()();
	if (E.isRight(result)) {
		return dirname(result.right.root);
	}
	return process.cwd();
};

/** Validate that a step name exists in the ordered steps list. */
const validateStepName = (
	stepName: string,
	orderedSteps: readonly OrderedStep[],
	optionName: string,
): void => {
	const validStepIds = orderedSteps.map((s) => s.id);
	if (!validStepIds.includes(stepName)) {
		console.error(
			chalk.red(
				`Error: Invalid step '${stepName}' for ${optionName}. Valid steps: ${validStepIds.join(", ")}`,
			),
		);
		process.exit(1);
	}
};

/** Emit a status_change event via executeEmit. */
const emitStatusChange = async (params: {
	runId: string;
	step?: string;
	unit?: string;
	status: string;
	workflow: string;
	feature: string;
	projectPath: string;
	closeRun?: boolean;
}): Promise<void> => {
	const input: EmitInput = {
		type: "status_change",
		runId: params.runId,
		step: params.step,
		unit: params.unit,
		data: {
			status: params.status,
			workflow: params.workflow,
			feature: params.feature,
		},
		projectPath: params.projectPath,
		closeRun: params.closeRun,
	};

	const result = await executeEmit(input)();
	if (E.isLeft(result)) {
		console.error(
			chalk.yellow(
				`Warning: Failed to emit event: ${JSON.stringify(result.left)}`,
			),
		);
	}
};

